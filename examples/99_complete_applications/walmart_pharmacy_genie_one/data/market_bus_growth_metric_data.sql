USE IDENTIFIER(:database);

-- Compact generative seed (INSERT ... SELECT over a store x date x metric grid).
-- A wide 105-column table makes literal VALUES impractical, so this stays committed
-- SQL provisioned via the config datasets: block (dao-ai workflow pipeline).

INSERT OVERWRITE market_bus_growth_metric
WITH d AS (SELECT explode(sequence(date_sub(current_date(),9), current_date(), interval 1 day)) AS calendar_date),
s AS (SELECT * FROM VALUES (1,1,1,1),(2,1,1,1),(3,1,1,1),(4,1,2,1),(5,2,2,1),(6,2,2,1),(7,2,3,2),(8,2,3,2),(9,3,3,2),(10,3,4,2),(11,3,4,2),(12,3,4,2) AS t(store_number, region_number, market_number, business_unit_i)),
m AS (SELECT explode(array('MESSAGING_ADOPTION_RATE','SYSTEMTIC_REFILL_PERCENTAGE','DOTCOM_REFILL_PERCENTAGE','AUTO_REFILL_PERCENTAGE','RXD_SCRIPT_PENETRATION','FIRST_TIME_ORDER_READY_RATE','RETURN_TO_STOCK_RATE','OUT_OF_STOCK_RATE','OUT_OF_STOCK_TRANSFER_RATE','WALK_IN_QR','NPS_SCORE','FIVE_STAR_RATE','VISITS','SCRIPTS_SALES','SCRIPTS_SOLD','OUT_OF_STOCK_TRANSFER','TESTING_AND_TREATEMENTS','HORMONAL_CONTRACEPTIVES','BASIC_HEALTH_SCREENINGS','TOTAL_ADMINISTERED','FLU_ADMINISTERED','EXPANDED_ADMINISTERED','NEW_DIGITAL_ACCOUNTS','NEW_DIGITAL_ACCOUNTS_OF_NEW_PATIENTS','NEW_DIGITAL_ACCOUNTS_OF_CONTINUING_PATIENTS','AVERAGE_ORDERS_SOLD_PER_STORE','AVERAGE_ORDERS_SOLD_PER_STORE_NEW')) AS metric_name)
SELECT
  d.calendar_date AS calendar_date,
  date_sub(d.calendar_date, 364) AS last_year_comparable_calendar_date,
  concat(CAST(year(d.calendar_date) AS STRING), lpad(CAST(weekofyear(d.calendar_date) AS STRING),2,'0')) AS walmart_year_week_number,
  CAST(weekofyear(d.calendar_date) AS INT) AS walmart_week_number,
  CAST(month(d.calendar_date) AS INT) AS walmart_month_number,
  date_format(d.calendar_date,'MMMM') AS walmart_month_name,
  CAST(quarter(d.calendar_date) AS INT) AS walmart_quarter_number,
  CAST(year(d.calendar_date) AS INT) AS walmart_year_number,
  CAST(month(d.calendar_date) AS INT) AS fiscal_month_number,
  date_format(d.calendar_date,'MMMM') AS fiscal_month_name,
  CAST(quarter(d.calendar_date) AS INT) AS fiscal_quarter_nbr,
  CAST(year(d.calendar_date) AS INT) AS fiscal_year_nbr,
  CAST(day(d.calendar_date) AS INT) AS current_calendar_day,
  1 AS week_to_date_flag,
  1 AS walmart_month_to_date_flag,
  1 AS walmart_quarter_to_date_flag,
  1 AS walmart_year_to_date_flag,
  1 AS fiscal_month_to_date_flag,
  1 AS fiscal_quarter_to_date_flag,
  1 AS fiscal_year_to_date_flag,
  'PHARMACY' AS line_of_business,
  CAST(s.business_unit_i AS STRING) AS business_unit,
  concat('Business Unit ', s.business_unit_i) AS business_unit_name,
  concat('BU-', s.business_unit_i) AS business_unit_display_name,
  s.region_number AS region_number,
  element_at(array('Northeast','Southeast','Midwest'), s.region_number) AS region_name,
  concat('Region ', s.region_number) AS region_display_name,
  s.market_number AS market_number,
  concat('Market ', s.market_number) AS market_name,
  concat('MKT-', s.market_number) AS market_display_name,
  s.store_number AS store_number,
  concat('Pharmacy #', s.store_number) AS store_name,
  concat('Store ', s.store_number) AS store_display_name,
  'OPEN' AS store_status,
  true AS is_active_store,
  (s.store_number % 2 = 0) AS comparable_store_flag,
  concat('SM ', s.store_number) AS store_manager_name,
  concat('MM ', s.market_number) AS market_manager_name,
  concat('RM ', s.region_number) AS region_manager_name,
  concat('BUM ', s.business_unit_i) AS bu_manager_name,
  'WMT' AS op_company_code,
  current_timestamp() AS load_time_stamp,
  'STORE' AS native_summary_grain,
  'market_bus_growth_metric' AS source_table,
  'PHARMACY_GROWTH' AS metric_group,
  m.metric_name AS metric_name,
  'rate' AS metric_type,
  'SUM' AS aggregation_rule,
  ROUND(rand()*1000,2) AS numerator_value_ty,
  ROUND(500+rand()*1000,2) AS denominator_value_ty,
  ROUND(rand()*100,2) AS metric_value_ty,
  ROUND(rand()*1000,2) AS numerator_value_ly,
  ROUND(500+rand()*1000,2) AS denominator_value_ly,
  ROUND(rand()*100,2) AS metric_value_ly,
  'num_rule' AS numerator_rule,
  'den_rule' AS denominator_rule,
  'FISCAL_CALENDAR' AS calendar_flag,
  element_at(array('WALKIN','DOTCOM','DELIVERY'), 1+CAST(rand()*3 AS INT)) AS order_channel,
  element_at(array('PICKUP','MAIL','COURIER'), 1+CAST(rand()*3 AS INT)) AS delivery_method,
  '[]' AS neighbouring_store_nbrs,
  '[]' AS neighbouring_market_nbrs,
  '[]' AS neighbouring_region_nbrs,
  '[]' AS neighbouring_subdiv_nbrs,
  CAST(year(current_date()) AS INT) AS current_walmart_year_number,
  CAST(year(current_date()) AS INT) AS current_fiscal_year_number,
  CAST(month(current_date()) AS INT) AS current_walmart_month_number,
  CAST(month(current_date()) AS INT) AS current_fiscal_month_number,
  CAST(quarter(current_date()) AS INT) AS current_walmart_quarter_number,
  CAST(quarter(current_date()) AS INT) AS current_fiscal_quarter_number,
  CAST(ROUND(60+rand()*38,1) AS STRING) AS store_outcomesone_successful_completion_rate_ytd,
  CAST(ROUND(60+rand()*38,1) AS STRING) AS market_outcomesone_successful_completion_rate_ytd,
  CAST(ROUND(60+rand()*38,1) AS STRING) AS region_outcomesone_successful_completion_rate_ytd,
  CAST(ROUND(60+rand()*38,1) AS STRING) AS bu_outcomesone_successful_completion_rate_ytd,
  CAST(ROUND(60+rand()*38,1) AS STRING) AS lob_outcomesone_successful_completion_rate_ytd,
  CAST(ROUND(60+rand()*38,1) AS STRING) AS store_completion_rate_ytd,
  CAST(ROUND(60+rand()*38,1) AS STRING) AS market_completion_rate_ytd,
  CAST(ROUND(60+rand()*38,1) AS STRING) AS region_completion_rate_ytd,
  CAST(ROUND(60+rand()*38,1) AS STRING) AS bu_completion_rate_ytd,
  CAST(ROUND(60+rand()*38,1) AS STRING) AS lob_completion_rate_ytd,
  CAST(ROUND(60+rand()*38,1) AS STRING) AS store_validation_rate_ytd,
  CAST(ROUND(60+rand()*38,1) AS STRING) AS market_validation_rate_ytd,
  CAST(ROUND(60+rand()*38,1) AS STRING) AS region_validation_rate_ytd,
  CAST(ROUND(60+rand()*38,1) AS STRING) AS bu_validation_rate_ytd,
  CAST(ROUND(60+rand()*38,1) AS STRING) AS lob_validation_rate_ytd,
  CAST(CAST(1000+rand()*2000000 AS BIGINT) AS STRING) AS store_digital_population,
  CAST(CAST(1000+rand()*2000000 AS BIGINT) AS STRING) AS market_digital_population,
  CAST(CAST(1000+rand()*2000000 AS BIGINT) AS STRING) AS region_digital_population,
  CAST(CAST(1000+rand()*2000000 AS BIGINT) AS STRING) AS bu_digital_population,
  CAST(CAST(1000+rand()*2000000 AS BIGINT) AS STRING) AS lob_digital_population,
  CAST(CAST(1000+rand()*2000000 AS BIGINT) AS STRING) AS store_active_patient_count_with_digital_accs,
  CAST(CAST(1000+rand()*2000000 AS BIGINT) AS STRING) AS market_active_patient_count_with_digital_accs,
  CAST(CAST(1000+rand()*2000000 AS BIGINT) AS STRING) AS region_active_patient_count_with_digital_accs,
  CAST(CAST(1000+rand()*2000000 AS BIGINT) AS STRING) AS bu_active_patient_count_with_digital_accs,
  CAST(CAST(1000+rand()*2000000 AS BIGINT) AS STRING) AS lob_active_patient_count_with_digital_accs,
  CAST(CAST(1000+rand()*2000000 AS BIGINT) AS STRING) AS store_active_patient_count_with_new_digital_accs,
  CAST(CAST(1000+rand()*2000000 AS BIGINT) AS STRING) AS market_active_patient_count_with_new_digital_accs,
  CAST(CAST(1000+rand()*2000000 AS BIGINT) AS STRING) AS region_active_patient_count_with_new_digital_accs,
  CAST(CAST(1000+rand()*2000000 AS BIGINT) AS STRING) AS bu_active_patient_count_with_new_digital_accs,
  CAST(CAST(1000+rand()*2000000 AS BIGINT) AS STRING) AS lob_active_patient_count_with_new_digital_accs,
  CAST(CAST(1000+rand()*2000000 AS BIGINT) AS STRING) AS store_active_patient_count_with_continuing_digital_accs,
  CAST(CAST(1000+rand()*2000000 AS BIGINT) AS STRING) AS market_active_patient_count_with_continuing_digital_accs,
  CAST(CAST(1000+rand()*2000000 AS BIGINT) AS STRING) AS region_active_patient_count_with_continuing_digital_accs,
  CAST(CAST(1000+rand()*2000000 AS BIGINT) AS STRING) AS bu_active_patient_count_with_continuing_digital_accs,
  CAST(CAST(1000+rand()*2000000 AS BIGINT) AS STRING) AS lob_active_patient_count_with_continuing_digital_accs
FROM d CROSS JOIN s CROSS JOIN m;
